/* ==========================================
   LANGUAGE STATE
   ========================================== */

let currentLanguage =
    localStorage.getItem("circleLanguage") || "en";


/* ==========================================
   CHANGE PAGE LANGUAGE
   ========================================== */

function setLanguage(language) {

    currentLanguage = language;

    localStorage.setItem(
        "circleLanguage",
        language
    );

    const t =
        translations[language];

    const html =
        document.documentElement;


    if (language === "ar") {

        html.setAttribute(
            "lang",
            "ar"
        );

        html.setAttribute(
            "dir",
            "rtl"
        );

    } else {

        html.setAttribute(
            "lang",
            "en"
        );

        html.setAttribute(
            "dir",
            "ltr"
        );

    }


    /* Navigation */

    document.getElementById(
        "languageToggle"
    ).textContent =
        t.languageButton;


    document.getElementById(
        "loginBtn"
    ).textContent =
        t.login;


    /* Hero */

    document.querySelector(
        ".badge"
    ).textContent =
        t.badge;


    const heroTitle =
        document.querySelector(
            ".hero h1"
        );


    heroTitle.childNodes[0]
        .textContent =
        t.heroTitle + " ";


    heroTitle.querySelector(
        "span"
    ).textContent =
        t.heroTitleSpan;


    document.querySelector(
        ".hero-content > p"
    ).textContent =
        t.heroDescription;


    document.getElementById(
        "startBtn"
    ).textContent =
        t.start;


    document.getElementById(
        "learnBtn"
    ).textContent =
        t.learn;


    document.querySelector(
        ".hero-note"
    ).textContent =
        t.heroNote;


    /* Hero Card */

    document.querySelector(
        ".card-header span:first-child"
    ).textContent =
        t.todayCircle;


    const metrics =
        document.querySelectorAll(
            ".metric"
        );


    if (metrics.length >= 4) {

        metrics[0]
            .querySelector(
                "div span:last-child"
            ).textContent =
            t.sleep;


        metrics[1]
            .querySelector(
                "div span:last-child"
            ).textContent =
            t.hydration;


        metrics[2]
            .querySelector(
                "div span:last-child"
            ).textContent =
            t.energy;


        metrics[3]
            .querySelector(
                "div span:last-child"
            ).textContent =
            t.stress;

    }


    document.querySelector(
        ".insight small"
    ).textContent =
        t.insightTitle;


    document.querySelector(
        ".insight p"
    ).textContent =
        t.insightText;


    /* How it works */

    const sections =
        document.querySelectorAll(
            ".section"
        );


    const howSection =
        sections[0];


    howSection.querySelector(
        ".eyebrow"
    ).textContent =
        t.howEyebrow;


    howSection.querySelector(
        "h2"
    ).textContent =
        t.howTitle;


    howSection.querySelector(
        ".section-title p"
    ).textContent =
        t.howDescription;


    const steps =
        howSection.querySelectorAll(
            ".step"
        );


    steps[0]
        .querySelector("h3")
        .textContent =
        t.step1Title;


    steps[0]
        .querySelector("p")
        .textContent =
        t.step1Text;


    steps[1]
        .querySelector("h3")
        .textContent =
        t.step2Title;


    steps[1]
        .querySelector("p")
        .textContent =
        t.step2Text;


    steps[2]
        .querySelector("h3")
        .textContent =
        t.step3Title;


    steps[2]
        .querySelector("p")
        .textContent =
        t.step3Text;


    /* Tracking */

    const trackSection =
        document.querySelector(
            ".track-section"
        );


    trackSection.querySelector(
        ".eyebrow"
    ).textContent =
        t.trackEyebrow;


    trackSection.querySelector(
        "h2"
    ).textContent =
        t.trackTitle;


    const trackCards =
        trackSection.querySelectorAll(
            ".track-card"
        );


    trackCards[0]
        .querySelector("h3")
        .textContent =
        t.sleep;


    trackCards[0]
        .querySelector("p")
        .textContent =
        t.sleepText;


    trackCards[1]
        .querySelector("h3")
        .textContent =
        t.hydration;


    trackCards[1]
        .querySelector("p")
        .textContent =
        t.hydrationText;


    trackCards[2]
        .querySelector("h3")
        .textContent =
        t.energy;


    trackCards[2]
        .querySelector("p")
        .textContent =
        t.energyText;


    trackCards[3]
        .querySelector("h3")
        .textContent =
        t.stress;


    trackCards[3]
        .querySelector("p")
        .textContent =
        t.stressText;


    /* AI */

    const aiSection =
        document.querySelector(
            ".ai-section"
        );


    aiSection.querySelector(
        ".eyebrow"
    ).textContent =
        t.aiEyebrow;


    aiSection.querySelector(
        "h2"
    ).textContent =
        t.aiTitle;


    aiSection.querySelector(
        ".ai-card > p"
    ).textContent =
        t.aiDescription;


    aiSection.querySelector(
        ".ai-example small"
    ).textContent =
        t.example;


    aiSection.querySelector(
        ".ai-example p"
    ).textContent =
        t.aiExample;


    aiSection.querySelector(
        ".disclaimer"
    ).textContent =
        t.aiDisclaimer;


    /* CTA */

    const cta =
        document.querySelector(
            ".cta"
        );


    cta.querySelector(
        "h2"
    ).textContent =
        t.ctaTitle;


    cta.querySelector(
        "p"
    ).textContent =
        t.ctaText;


    document.getElementById(
        "ctaBtn"
    ).textContent =
        t.getStarted;


    /* Medical Disclaimer */

    const disclaimerSection =
        document.querySelector(
            ".disclaimer-section"
        );


    disclaimerSection.querySelector(
        "h3"
    ).textContent =
        t.medicalTitle;


    disclaimerSection.querySelector(
        "p"
    ).textContent =
        t.medicalText;


    /* Footer */

    document.querySelector(
        "footer p"
    ).textContent =
        t.copyright;

}


/* ==========================================
   LANGUAGE BUTTON
   ========================================== */

document
    .getElementById(
        "languageToggle"
    )
    .addEventListener(
        "click",
        function () {

            if (
                currentLanguage === "en"
            ) {

                setLanguage("ar");

            } else {

                setLanguage("en");

            }

        }
    );


/* ==========================================
   LEARN MORE
   ========================================== */

document
    .getElementById(
        "learnBtn"
    )
    .addEventListener(
        "click",
        function () {

            document
                .getElementById(
                    "howItWorks"
                )
                .scrollIntoView({
                    behavior:
                        "smooth"
                });

        }
    );


/* ==========================================
   START BUTTONS
   ========================================== */

